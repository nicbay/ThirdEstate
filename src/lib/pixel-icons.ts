export type PixelIcon = keyof typeof ICONS;

/** Inline SVG of a pixel icon, horizontal runs merged into one <rect>. */
export function pixelIcon(name: PixelIcon, size = 24) {
  let rects = "";
  ICONS[name].forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) rects += `<rect x="${m.index}" y="${y}" width="${m[0].length}" height="1"/>`;
  });
  return `<svg class="px-icon" viewBox="0 0 12 12" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
